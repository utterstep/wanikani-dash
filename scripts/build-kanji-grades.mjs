#!/usr/bin/env node
// Regenerate js/kanji-grades.js from KANJIDIC2.
//
//   npm pack kanjidic2-json && tar xzf kanjidic2-json-*.tgz
//   node scripts/build-kanji-grades.mjs package/KANJIS.json
//
// KANJIDIC2 grade codes: 1–6 = kyōiku (school grade), 8 = the remaining jōyō
// kanji taught in secondary school, 9–10 = jinmeiyō. The dataset must carry the
// 2017 revision (effective 2020) — check that the 20 prefecture kanji sit in
// grade 4 and that grades 1–6 hold 1026 kanji; the script refuses otherwise.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const src = process.argv[2];
if (!src) {
  console.error('usage: build-kanji-grades.mjs <path to KANJIDIC2 KANJIS.json>');
  process.exit(2);
}

const EXPECTED = { 1: 80, 2: 160, 3: 200, 4: 202, 5: 193, 6: 191, 8: 1110 };
const PREFECTURE = '茨媛岡潟岐熊香佐埼崎滋鹿縄井沖栃奈梨阪阜';

const kanjis = JSON.parse(readFileSync(src, 'utf8'));
const buckets = new Map();
for (const k of kanjis) {
  const g = k.grade;
  if (!g) continue;
  const key = g <= 6 ? String(g) : g === 8 ? 'S' : 'J';
  if (!buckets.has(key)) buckets.set(key, []);
  buckets.get(key).push(k.literal);
}
for (const list of buckets.values()) list.sort((a, b) => a.codePointAt(0) - b.codePointAt(0));

const size = (k) => (buckets.get(k) ?? []).length;
const problems = [];
for (const [g, n] of Object.entries(EXPECTED)) {
  const key = g === '8' ? 'S' : g;
  if (size(key) !== n) problems.push(`grade ${g}: expected ${n} kanji, got ${size(key)}`);
}
for (const c of PREFECTURE) {
  if (!buckets.get('4')?.includes(c)) problems.push(`${c} is not in grade 4 — source predates the 2017 kyōiku revision`);
}
if (problems.length) {
  console.error('Refusing to write:\n  ' + problems.join('\n  '));
  process.exit(1);
}

const ORDER = ['1', '2', '3', '4', '5', '6', 'S'];
const joyo = ORDER.map((k) => `  ${k === 'S' ? "S:" : `'${k}':`} '${buckets.get(k).join('')}',`).join('\n');
const out = `// GENERATED by scripts/build-kanji-grades.mjs — do not edit by hand.
//
// Kanji grouped by Jōyō (常用漢字) school grade, from KANJIDIC2.
// Keys '1'–'6' are the kyōiku grades (小学1年–6年, 1026 kanji after the 2017
// revision); 'S' is the rest of the Jōyō list, taught in secondary school
// (中学校以上, 1110 kanji). J is the Jinmeiyō (人名用漢字) supplement.
//
// Source: KANJIDIC2 © the Electronic Dictionary Research and Development Group,
// used under CC BY-SA 4.0 — https://www.edrdg.org/edrdg/licence.html
// Obtained via the npm package \`kanjidic2-json\`.

/** @type {Record<'1'|'2'|'3'|'4'|'5'|'6'|'S', string>} */
export const JOYO_BY_GRADE = {
${joyo}
};

/** Jinmeiyō kanji — the name-use supplement to the Jōyō list, not part of it. */
export const JINMEIYO = '${buckets.get('J').join('')}';

export const GRADE_KEYS = ${JSON.stringify(ORDER)};

export const GRADE_LABEL = {
  1: 'Grade 1', 2: 'Grade 2', 3: 'Grade 3', 4: 'Grade 4', 5: 'Grade 5', 6: 'Grade 6',
  S: 'Secondary', J: 'Jinmeiyō',
};

const index = new Map();
for (const key of GRADE_KEYS) for (const ch of JOYO_BY_GRADE[key]) index.set(ch, key);
for (const ch of JINMEIYO) if (!index.has(ch)) index.set(ch, 'J');

/** '1'–'6' | 'S' (secondary-school jōyō) | 'J' (jinmeiyō) | null (neither list). */
export function gradeOf(ch) {
  return index.get(ch) ?? null;
}

export function isJoyo(ch) {
  const g = index.get(ch);
  return !!g && g !== 'J';
}
`;

const here = dirname(fileURLToPath(import.meta.url));
const dest = join(here, '..', 'js', 'kanji-grades.js');
writeFileSync(dest, out);
console.log(`wrote ${dest}`);
console.log(ORDER.map((k) => `${k}:${size(k)}`).join(' '), `J:${size('J')}`, `jōyō total ${ORDER.reduce((n, k) => n + size(k), 0)}`);
